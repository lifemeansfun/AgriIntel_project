const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require('/Users/manishharigovind/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
(async () => {
  const browser = await chromium.launch({headless:true,args:['--enable-webgl','--use-gl=angle','--use-angle=swiftshader']});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const report = {checks:[],errors:[],screenshots:[],warnings:[]};
  page.on('pageerror', e=>report.errors.push(e.message));
  page.on('console', e=>{if(e.type()==='error')report.errors.push(e.text());else if(e.type()==='warning')report.warnings.push(e.text());});
  const save=async(name)=>{const p=path.join(__dirname,name+'.png');await page.screenshot({path:p});report.screenshots.push(p);};
  try {
    await page.goto('http://127.0.0.1:5174',{waitUntil:'networkidle'});
    await page.waitForTimeout(2600);
    await page.waitForFunction(()=>document.querySelector('#advisory-scenario')?.options.length===2);
    const id=await page.locator('#advisory-scenario option').nth(1).getAttribute('value');
    await page.locator('#advisory-scenario').selectOption(id);
    await page.locator('#demo-participant').fill('final-visual-'+Date.now());
    const response=page.waitForResponse(r=>r.url().endsWith('/recommendations')&&r.request().method()==='POST');
    await page.locator('#aperture-submit-btn').click();
    const rows=(await (await response).json()).recommendations;
    const card=page.getByRole('region',{name:rows[0].Crop+' recommendation',exact:true});
    await card.waitFor();
    await card.scrollIntoViewIfNeeded();
    await page.waitForTimeout(400);
    const profit=card.locator('p.font-mono-tech.font-bold').first();
    const lightColor=await profit.evaluate(e=>getComputedStyle(e).color);
    await save('final-desktop-day');
    await page.getByRole('button',{name:'Toggle day/night theme'}).click();
    await page.waitForTimeout(500);
    await card.scrollIntoViewIfNeeded();
    assert.ok(await page.locator('html').evaluate(e=>e.classList.contains('dark')));
    const darkColor=await profit.evaluate(e=>getComputedStyle(e).color);
    assert.notEqual(darkColor,lightColor);
    assert.equal(darkColor,'oklch(0.845 0.143 164.978)');
    await save('final-desktop-night');
    report.checks.push({name:'Theme toggle controls Tailwind contrast',lightColor,darkColor});
    const points=page.locator('.recharts-scatter-symbol');
    assert.equal(await points.count(),3);
    await points.first().scrollIntoViewIfNeeded();
    await save('final-chart-points');
    report.checks.push({name:'Three crop chart points render without animation delay',points:3});
    await page.setViewportSize({width:375,height:812});
    await page.evaluate(()=>window.scrollTo(0,0));
    await page.waitForTimeout(400);
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await save('final-mobile-night-controls');
    await card.scrollIntoViewIfNeeded();
    await save('final-mobile-night-crop');
    await page.getByRole('button',{name:'Toggle day/night theme'}).click();
    await page.waitForTimeout(300);
    await card.scrollIntoViewIfNeeded();
    await save('final-mobile-day-crop');
    report.checks.push({name:'375px light/dark remain within viewport'});
    await page.locator('#inspect-analytics-btn').click();
    await page.getByRole('heading',{name:rows[0].Crop,exact:true,level:1}).waitFor();
    assert.ok((await page.locator('body').innerText()).includes('Cultivation cost'));
    await save('final-mobile-analytics');
    report.checks.push({name:'Scenario calculation details render on mobile'});
    assert.equal(report.errors.length,0,JSON.stringify(report.errors));
    report.status='pass';
  }catch(e){report.status='fail';report.failure=e.message;console.error(e);}
  finally{fs.writeFileSync(path.join(__dirname,'browser-final-visual.json'),JSON.stringify(report,null,2));await browser.close();console.log(JSON.stringify(report,null,2));if(report.status!=='pass')process.exitCode=1;}
})();
